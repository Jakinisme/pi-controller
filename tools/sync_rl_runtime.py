"""Vendor the DRL R7 policy runtime into this repo.

    .venv/Scripts/python.exe tools/sync_rl_runtime.py [--drl E:/buoy-project/drl]
        [--onnx runs/r7_policy.onnx] [--meta runs/r7_policy_meta.json] [--check]

Copies (with the documented import rewrites) into `src/rl/`:

    drl/runtime/policy.py    -> src/rl/policy.py
    drl/runtime/obs_np.py    -> src/rl/obs_np.py
    drl/common/estimator.py  -> src/rl/estimator.py
    drl/common/frames.py     -> src/rl/frames.py

Import rewrites applied (the only differences from the DRL sources):

    policy.py : from common.estimator import  -> from src.rl.estimator import
                from common.frames import     -> from src.rl.frames import
                from runtime.obs_np import    -> from src.rl.obs_np import
    obs_np.py : from common.frames import     -> from src.rl.frames import

and `--onnx`/`--meta` (default R7, the newest checkpoint) into `models/policy.onnx`
and `models/policy_meta.json`, then writes `models/MANIFEST.json` (sha256 + size of
every copied file, DRL git HEAD, checkpoint provenance).

Idempotent: a file whose content already matches is not rewritten, and MANIFEST.json
is only rewritten when its content (excluding `synced_utc`) actually changes.
`--check` writes nothing: exit 0 if vendored copy + model + manifest match DRL,
exit 1 with a per-file diff list otherwise. Nothing is ever written inside DRL.

ponytail: exact-path replacement of whole import lines, not a real import-graph
rewrite — the DRL files import each other by absolute path only, so this covers them;
upgrade to `ast` rewriting if a vendored file ever gains a new intra-repo import.
"""

import argparse
import hashlib
import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DRL = Path("E:/buoy-project/drl")
DEFAULT_ONNX = "runs/r7_policy.onnx"
DEFAULT_META = "runs/r7_policy_meta.json"
MANIFEST = "models/MANIFEST.json"

# (drl-relative source, repo-relative target, import rewrite pairs)
PY_FILES = (
    ("runtime/policy.py", "src/rl/policy.py", (
        ("from common.estimator import", "from src.rl.estimator import"),
        ("from common.frames import", "from src.rl.frames import"),
        ("from runtime.obs_np import", "from src.rl.obs_np import"),
    )),
    # obs_np.py also has one intra-repo import the interface assumed absent:
    # `from common.frames import ...`. Same rewrite as policy.py; see report.
    ("runtime/obs_np.py", "src/rl/obs_np.py", (
        ("from common.frames import", "from src.rl.frames import"),
    )),
    ("common/estimator.py", "src/rl/estimator.py", ()),
    ("common/frames.py", "src/rl/frames.py", ()),
)

VENDOR_NOTE = '''"""Vendored DRL runtime — GENERATED by `tools/sync_rl_runtime.py`. Do not edit.

`src/rl/policy.py`, `obs_np.py`, `estimator.py`, `frames.py` are byte-copies of
`drl/runtime/policy.py`, `drl/runtime/obs_np.py`, `drl/common/estimator.py`,
`drl/common/frames.py` with these import rewrites only:

    policy.py : from common.estimator import   ->  from src.rl.estimator import
                from common.frames import      ->  from src.rl.frames import
                from runtime.obs_np import     ->  from src.rl.obs_np import
    obs_np.py : from common.frames import      ->  from src.rl.frames import

`models/policy.onnx` + `models/policy_meta.json` are the R7 export
(`drl/runs/r7_policy.onnx` + `r7_policy_meta.json`). Hashes, DRL commit and
checkpoint provenance live in `models/MANIFEST.json`.

Hand edits are lost on the next `tools/sync_rl_runtime.py` run; `--check` fails on
any drift from the DRL source. Fix the policy in the DRL repo and re-sync.
"""
'''


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def rewrite(text, pairs):
    for old, new in pairs:
        text = text.replace(old, new)
    return text


def drl_commit(drl):
    try:
        out = subprocess.run(["git", "-C", str(drl), "rev-parse", "HEAD"],
                             capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    return out.stdout.strip() if out.returncode == 0 and out.stdout.strip() else "unknown"


def read(path):
    return Path(path).read_bytes()


def plan(drl, onnx_rel, meta_rel, manifest_root):
    """Build the full expected repo state: [(rel_path, bytes)] + manifest dict."""
    meta_src = drl / meta_rel
    meta = json.loads(meta_src.read_text(encoding="utf-8"))
    expected, files = [], {}
    for src_rel, dst_rel, pairs in PY_FILES:
        data = rewrite(read(drl / src_rel).decode("utf-8"), pairs).encode("utf-8")
        expected.append((dst_rel, data))
        files[dst_rel] = {"sha256": sha256(data), "bytes": len(data), "src": src_rel}
    expected.append(("src/rl/_vendor_note.py", VENDOR_NOTE.encode("utf-8")))
    for src_rel, dst_rel in ((onnx_rel, "models/policy.onnx"),
                             (meta_rel, "models/policy_meta.json")):
        data = read(drl / src_rel)
        expected.append((dst_rel, data))
        files[dst_rel] = {"sha256": sha256(data), "bytes": len(data), "src": src_rel}
    expected.append((MANIFEST, None))  # placeholder, filled by write_manifest
    info = {
        "drl_commit": drl_commit(drl),
        "drl_path": manifest_root,
        "checkpoint_steps": meta.get("steps"),
        "iteration": meta.get("iteration"),
        "source_ckpt": meta.get("source_ckpt"),
        "files": files,
    }
    return expected, info


def manifest_body(info):
    return {"synced_utc": None, **info}


def write_manifest(info, old_path):
    body = manifest_body(info)
    try:
        old = json.loads(old_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        old = None
    # keep `synced_utc` stable when nothing else changed
    if old is not None and {k: v for k, v in old.items() if k != "synced_utc"} == info:
        return False
    body["synced_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    old_path.write_text(json.dumps(body, indent=2, sort_keys=True) + "\n",
                        encoding="utf-8")
    return True


def manifest_drift(info, path):
    """List of strings describing how the on-disk manifest differs from `info`."""
    try:
        cur = json.loads(path.read_text(encoding="utf-8"))
    except OSError:
        return [f"{MANIFEST}: missing"]
    except ValueError:
        return [f"{MANIFEST}: unparseable JSON"]
    diffs = []
    for key in ("drl_commit", "drl_path", "checkpoint_steps", "iteration", "source_ckpt"):
        if cur.get(key) != info[key]:
            diffs.append(f"{MANIFEST}: {key} {cur.get(key)!r} != {info[key]!r}")
    cur_files = cur.get("files") or {}
    for rel, want in info["files"].items():
        got = cur_files.get(rel)
        if not isinstance(got, dict):
            diffs.append(f"{MANIFEST}: no entry for {rel}")
        elif got.get("sha256") != want["sha256"] or got.get("src") != want["src"]:
            diffs.append(f"{MANIFEST}: stale entry for {rel}")
    for rel in cur_files:
        if rel not in info["files"]:
            diffs.append(f"{MANIFEST}: extra entry for {rel}")
    return diffs


def main(argv=None):
    ap = argparse.ArgumentParser(prog="sync_rl_runtime", description=__doc__.splitlines()[0])
    ap.add_argument("--drl", default=str(DEFAULT_DRL))
    ap.add_argument("--onnx", default=DEFAULT_ONNX)
    ap.add_argument("--meta", default=DEFAULT_META)
    ap.add_argument("--check", action="store_true",
                    help="verify only, write nothing; exit 1 on drift")
    a = ap.parse_args(argv)

    drl = Path(a.drl).resolve()
    if not drl.is_dir():
        print(f"error: DRL repo not found: {drl} (pass --drl <path>)", file=sys.stderr)
        return 2
    for rel in [s for s, _, _ in PY_FILES] + [a.onnx, a.meta]:
        if not (drl / rel).is_file():
            print(f"error: missing in DRL repo: {drl / rel}", file=sys.stderr)
            return 2

    try:
        manifest_root = drl.relative_to(ROOT.parent).as_posix()
    except ValueError:
        manifest_root = drl.as_posix()
    if ":" not in manifest_root and manifest_root.startswith(".."):
        manifest_root = ROOT.as_posix()  # ponytail: cross-drive fallback, no relpath

    expected, info = plan(drl, a.onnx, a.meta, manifest_root)
    changes, diffs = [], []
    for rel, data in expected:
        dst = ROOT / rel
        if data is None:  # MANIFEST handled separately
            continue
        cur = dst.read_bytes() if dst.is_file() else None
        state = "unchanged" if cur == data else ("changed" if cur is not None else "created")
        if state != "unchanged":
            changes.append((rel, state))
        print(f"{state:<9} {rel}")

    if a.check:
        diffs += [f"{rel}: {state} (differs from rewrite of DRL source)"
                  for rel, state in changes]
        diffs += manifest_drift(info, ROOT / MANIFEST)
        if diffs:
            print("\ndrift detected:")
            for d in diffs:
                print(f"  {d}")
            return 1
        print("\nin sync")
        return 0

    for rel, state in changes:
        dst = ROOT / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(dict(expected)[rel])
    wrote = write_manifest(info, ROOT / MANIFEST)
    print(f"{'written' if wrote else 'unchanged'} {MANIFEST}")
    print(f"\n{len(changes)} file(s) changed, {len(expected) - 1 - len(changes)} unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
